-- Conocimiento, producto mínimo (3 de 3): lo que hace cada usuario. Lecturas
-- terminadas, estado del repaso de cada reto y respuestas.
--
-- Las tres cuelgan de usuario con FK NOT NULL y sin ON DELETE CASCADE: las
-- borra LimpiadorConocimiento en la baja de la cuenta y las exporta
-- ExportadorConocimiento (RGPD).
--
-- clave es el UUID que genera la app; única, para que un reintento (la cola
-- sin conexión) no pague dos veces: el patrón de sesion_enfoque (V26).
-- dia es el día en la zona del usuario: la racha y el tope diario del premio
-- se cuentan por él. Los TIMESTAMP (leida_en, respondida_en, ultimo_repaso,
-- vence_en) van en UTC.
-- premio_monedas, premio_xp, premio_logros y premio_tope: lo que pagó esa
-- fila, ya recortado por el tope del día, como en sesion_enfoque (V27). Se
-- guardan para que un reintento devuelva el premio original sin volver a
-- pagarlo. premio_logros: códigos separados por comas; NULL si ninguno.

-- Una fila por lectura terminada de una píldora.
CREATE TABLE lectura_pildora (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INTEGER       NOT NULL,
    pildora_id     INTEGER       NOT NULL,
    clave          UUID          NOT NULL,
    dia            DATE          NOT NULL,
    leida_en       TIMESTAMP     NOT NULL,
    premio_monedas INTEGER       NOT NULL DEFAULT 0,
    premio_xp      INTEGER       NOT NULL DEFAULT 0,
    premio_logros  VARCHAR(1000),
    premio_tope    BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT UK_lectura_pildora_clave UNIQUE (clave),
    CONSTRAINT FK_lectura_pildora_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id),
    CONSTRAINT FK_lectura_pildora_pildora
        FOREIGN KEY (pildora_id) REFERENCES pildora (pildora_id)
);

CREATE INDEX idx_lectura_pildora_usuario_dia ON lectura_pildora (usuario_id, dia);

-- El estado del repaso (FSRS) de cada reto para cada usuario. Se crea al leer
-- la píldora; un reto está en la bandeja si vence_en ya pasó.
-- repasos = 0: todavía no se ha respondido nunca. Entonces estabilidad y
-- dificultad valen 0 y no significan nada (FSRS no tiene estado antes del
-- primer repaso, y tras él la estabilidad siempre es mayor que 0).
-- DOUBLE PRECISION y no NUMERIC: los campos de la entidad son double (V5).
CREATE TABLE usuario_reto (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    INTEGER          NOT NULL,
    reto_id       INTEGER          NOT NULL,
    estabilidad   DOUBLE PRECISION NOT NULL DEFAULT 0,
    dificultad    DOUBLE PRECISION NOT NULL DEFAULT 0,
    repasos       INTEGER          NOT NULL DEFAULT 0,
    fallos        INTEGER          NOT NULL DEFAULT 0,
    ultimo_repaso TIMESTAMP,
    vence_en      TIMESTAMP        NOT NULL,
    CONSTRAINT UK_usuario_reto UNIQUE (usuario_id, reto_id),
    CONSTRAINT FK_usuario_reto_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id),
    CONSTRAINT FK_usuario_reto_reto
        FOREIGN KEY (reto_id) REFERENCES reto (reto_id)
);

-- La bandeja: los retos vencidos de un usuario, del más antiguo al más nuevo.
CREATE INDEX idx_usuario_reto_vence ON usuario_reto (usuario_id, vence_en);

-- Una fila por respuesta a un reto. opcion cuenta desde 0, como
-- reto.indice_correcta; acierto se guarda (no se recalcula) porque el reto
-- puede cambiar después en el repo.
CREATE TABLE respuesta_reto (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INTEGER       NOT NULL,
    reto_id        INTEGER       NOT NULL,
    clave          UUID          NOT NULL,
    opcion         INTEGER       NOT NULL,
    acierto        BOOLEAN       NOT NULL,
    dia            DATE          NOT NULL,
    respondida_en  TIMESTAMP     NOT NULL,
    premio_monedas INTEGER       NOT NULL DEFAULT 0,
    premio_xp      INTEGER       NOT NULL DEFAULT 0,
    premio_logros  VARCHAR(1000),
    premio_tope    BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT UK_respuesta_reto_clave UNIQUE (clave),
    CONSTRAINT FK_respuesta_reto_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id),
    CONSTRAINT FK_respuesta_reto_reto
        FOREIGN KEY (reto_id) REFERENCES reto (reto_id)
);

CREATE INDEX idx_respuesta_reto_usuario_dia ON respuesta_reto (usuario_id, dia);
