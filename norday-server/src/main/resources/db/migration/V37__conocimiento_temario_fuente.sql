-- Conocimiento, producto mínimo (1 de 3): temarios, fuentes y lo que gana la
-- píldora. Especificación: «Norday Conocimiento — Especificación técnica del
-- producto mínimo», sección Modelo de datos.
--
-- El contenido llega de un repo propio (norday_conocimiento_contenido) por un
-- importador que actualiza por codigo, nunca por id: por eso cada tabla de
-- contenido tiene un codigo único y estable. Nada de contenido se borra: lo
-- que sale del repo pasa a activo/activa = false, porque las filas de los
-- usuarios (lecturas, respuestas, repasos) siguen apuntando a ello.
--
-- Las claves primarias de V37-V39 son GENERATED BY DEFAULT AS IDENTITY, como
-- las de V4, y no SERIAL como V26: es lo que genera Hibernate en los tests, y
-- así el esquema de las migraciones y el de los tests son el mismo (salvo el
-- CHECK que Hibernate añade a las columnas enum, que no se replica).
--
-- temario: un recorrido ordenado dentro de una rama (categoria_conocimiento).
CREATE TABLE temario (
    temario_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(100) NOT NULL,
    categoria_id INTEGER      NOT NULL,
    titulo       VARCHAR(200) NOT NULL,
    descripcion  VARCHAR(500),
    orden        INTEGER      NOT NULL,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT UK_temario_codigo UNIQUE (codigo),
    CONSTRAINT FK_temario_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria_conocimiento (categoria_id)
);

CREATE INDEX idx_temario_categoria ON temario (categoria_id);

-- fuente: el libro del «Para saber más» y las fuentes citables. La procedencia
-- completa, afirmación por afirmación, se queda en el repo de contenido.
-- tipo: LIBRO, PAPER o DOMINIO_PUBLICO. licencia: la de la fuente, en texto
-- libre corto (no se valida aquí: lo valida el importador).
CREATE TABLE fuente (
    fuente_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(100) NOT NULL,
    tipo      VARCHAR(20)  NOT NULL,
    titulo    VARCHAR(300) NOT NULL,
    autor     VARCHAR(200),
    anio      INTEGER,
    url       VARCHAR(500),
    licencia  VARCHAR(30),
    CONSTRAINT UK_fuente_codigo UNIQUE (codigo)
);

-- pildora gana:
--   codigo         la clave del importador. Admite NULL porque la columna se
--                  añade a una tabla que ya existe en producción (V4); dos
--                  NULL no chocan con el UNIQUE. Toda píldora importada lo trae.
--   temario_id     NULL para las píldoras sueltas, que solo salen en el match.
--   orden_temario  su posición en el temario; NULL si es suelta. No lleva
--                  UNIQUE (temario_id, orden_temario): al reordenar un temario
--                  la restricción se incumpliría a mitad del cambio (la
--                  lección de usuario_equipado). Que no se repita lo comprueba
--                  validar.py antes de importar.
--   nivel          1 de entrada; sube en los temarios largos.
--   version        sube con cada cambio de texto en el repo. Una píldora con
--                  la misma version que la de aquí no se toca al importar.
--   fuente_id      el libro que la amplía («Para saber más»); NULL si no hay.
--   licencia       la del texto de la píldora (texto-propio, cc-by, cc0,
--                  dominio-publico). Sin DEFAULT a propósito: una licencia no
--                  se supone, la declara el repo.
-- preview_corto pasa a ser el gancho y contenido_completo guarda las tarjetas
-- unidas (biblioteca y compartir). libro_origen queda obsoleto: el importador
-- lo rellena con «Autor, Título» por compatibilidad.
ALTER TABLE pildora
    ADD COLUMN codigo        VARCHAR(100),
    ADD COLUMN temario_id    INTEGER,
    ADD COLUMN orden_temario INTEGER,
    ADD COLUMN nivel         INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN version       INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN fuente_id     INTEGER,
    ADD COLUMN licencia      VARCHAR(30),
    ADD CONSTRAINT UK_pildora_codigo UNIQUE (codigo),
    ADD CONSTRAINT FK_pildora_temario
        FOREIGN KEY (temario_id) REFERENCES temario (temario_id),
    ADD CONSTRAINT FK_pildora_fuente
        FOREIGN KEY (fuente_id) REFERENCES fuente (fuente_id);

-- Para servir un temario en orden.
CREATE INDEX idx_pildora_temario ON pildora (temario_id, orden_temario);

-- usuario_pildora.estado gana EN_COLA y LEIDA (ver EstadoPildora). La columna
-- es VARCHAR(30) y V4 la creó sin CHECK, pero una tabla generada por Hibernate
-- 6 (una base local antigua, o una reconstruida desde las entidades) lleva un
-- CHECK con solo DESCARTADA, VISTA y GUARDADA, y la primera escritura de los
-- valores nuevos fallaría (23514). Se quita si existe; si no, no hace nada.
ALTER TABLE usuario_pildora DROP CONSTRAINT IF EXISTS usuario_pildora_estado_check;
