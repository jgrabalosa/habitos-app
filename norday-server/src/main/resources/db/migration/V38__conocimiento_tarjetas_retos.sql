-- Conocimiento, producto mínimo (2 de 3): las tarjetas de cada píldora y sus
-- retos (las preguntas que llegan después a la bandeja).
--
-- pildora_tarjeta: las 3-5 tarjetas que se leen una tras otra. El gancho no es
-- una tarjeta: vive en pildora.preview_corto. UNIQUE (pildora_id, orden)
-- porque dos tarjetas en el mismo sitio no tienen sentido. Ojo para el
-- importador: al rehacer las tarjetas de una píldora hay que borrar las viejas
-- y vaciar (flush) antes de insertar las nuevas; Hibernate inserta antes de
-- borrar y la restricción saltaría.
CREATE TABLE pildora_tarjeta (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pildora_id INTEGER NOT NULL,
    orden      INTEGER NOT NULL,
    texto      TEXT    NOT NULL,
    CONSTRAINT UK_pildora_tarjeta_orden UNIQUE (pildora_id, orden),
    CONSTRAINT FK_pildora_tarjeta_pildora
        FOREIGN KEY (pildora_id) REFERENCES pildora (pildora_id)
);

-- reto: la pregunta de opción múltiple de una píldora (1 o 2 por píldora).
-- indice_correcta cuenta desde 0 sobre reto_opcion.orden. INTEGER y no
-- SMALLINT: el campo de la entidad es un int, y con SMALLINT el perfil local
-- (ddl-auto=validate) no arranca (la lección de V5, en otro tipo).
-- activo: el importador retira, nunca borra; usuario_reto y respuesta_reto
-- siguen apuntando aquí.
CREATE TABLE reto (
    reto_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(100)  NOT NULL,
    pildora_id      INTEGER       NOT NULL,
    enunciado       VARCHAR(500)  NOT NULL,
    indice_correcta INTEGER       NOT NULL,
    explicacion     VARCHAR(1000),
    activo          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT UK_reto_codigo UNIQUE (codigo),
    CONSTRAINT FK_reto_pildora
        FOREIGN KEY (pildora_id) REFERENCES pildora (pildora_id)
);

CREATE INDEX idx_reto_pildora ON reto (pildora_id);

-- reto_opcion: las opciones de un reto, en orden (2 a 4). En la entidad es un
-- @ElementCollection con @OrderColumn: la clave primaria es (reto_id, orden),
-- la misma que genera Hibernate en los tests.
CREATE TABLE reto_opcion (
    reto_id INTEGER      NOT NULL,
    orden   INTEGER      NOT NULL,
    texto   VARCHAR(300) NOT NULL,
    CONSTRAINT PK_reto_opcion PRIMARY KEY (reto_id, orden),
    CONSTRAINT FK_reto_opcion_reto
        FOREIGN KEY (reto_id) REFERENCES reto (reto_id)
);
